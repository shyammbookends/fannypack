// Shrinks Bootstrap to the classes the site actually uses.
// Input:  src/assets/css/bootstrap.full.min.css (the complete Bootstrap 5.3 build - keep it)
// Output: src/assets/css/bootstrap.min.css      (what the site imports)
// Usage:  npm run css:purge   - run it again after using a new Bootstrap class (e.g. "col-xl-3", "d-md-flex").
// PurgeCSS is only needed while running this (it is not a project dependency): npm i --no-save purgecss@7
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

let PurgeCSS;
try {
  ({ PurgeCSS } = await import('purgecss'));
} catch {
  console.error('PurgeCSS is not installed. Run:  npm i --no-save purgecss@7   then  npm run css:purge');
  process.exit(1);
}

const ROOT = path.resolve(import.meta.dirname, '..');
const input = path.join(ROOT, 'src/assets/css/bootstrap.full.min.css');
const output = path.join(ROOT, 'src/assets/css/bootstrap.min.css');

const [result] = await new PurgeCSS().purge({
  content: [path.join(ROOT, 'src/**/*.{js,jsx}'), path.join(ROOT, 'index.html'), path.join(ROOT, '../backend/lib/content.js')],
  css: [input],
  // class names are built with strings in some places ('col-sm-' + n, conditional 'show'), so keep whole families
  safelist: {
    standard: ['show', 'collapse', 'collapsing', 'active', 'disabled', 'navbar-collapse', 'navbar-expand-lg', 'container', 'container-fluid', 'row', 'col'],
    greedy: [/^col-/, /^g-/, /^gx-/, /^gy-/, /^row-cols-/, /^navbar/, /^nav-/, /^d-/, /^justify-content-/, /^align-items-/, /^align-self-/, /^flex-/, /^order-/, /^offset-/, /^text-/, /^m[tbsexy]?-/, /^p[tbsexy]?-/, /^w-/, /^h-/, /^gap-/],
    variables: [/^--bs-/],
  },
  variables: false,
  keyframes: true,
  fontFace: true,
});
const header = '/* Bootstrap 5.3 (MIT) - only the classes used by this site. Generated by scripts/purge-bootstrap.mjs */\n';
await writeFile(output, header + result.css);
const before = (await readFile(input)).length;
console.log(`bootstrap.min.css: ${Math.round(before / 1024)} KB -> ${Math.round(result.css.length / 1024)} KB`);
